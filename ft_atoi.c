#include "libft.h"

int	ft_atoi(const char *str)
{
	int	i;
	int	count;
	int	sign;
	int	result;

	i = 0;
	count = 0;
	sign = 1;
	result = 0;
	while ((str[i] >= 9 && str[i] <= 13) || str[i] == 32)
		i++;
	while (str[i] == '-' || str[i] == '+')
	{
		count++;
		if (str[i] == '-')
			sign = -1;
		if (count > 1)
			return (0);
		i++;
	}
	while (str[i] >= '0' && str[i] <= '9')
	{
		result = result * 10 + (str[i] - 48);
		i++;
	}
	return (result * sign);
}
